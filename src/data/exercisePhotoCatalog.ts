export function findCuratedPhotoForExercise(exerciseName: string, primaryMuscle?: string): string | null {
  const norm = (exerciseName || '')
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();

  for (const [key, urls] of Object.entries(CURATED_WEB_EXERCISE_PHOTOS)) {
    const normKey = key
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .trim();

    if (norm.includes(normKey) || normKey.includes(norm)) {
      if (urls.length > 0) return urls[0];
    }
  }

  if (primaryMuscle && MUSCLE_FALLBACK_PHOTOS[primaryMuscle] && MUSCLE_FALLBACK_PHOTOS[primaryMuscle].length > 0) {
    return MUSCLE_FALLBACK_PHOTOS[primaryMuscle][0];
  }

  return null;
}
